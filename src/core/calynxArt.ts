/** Horizontal runs of '#' cells: [x, y, length], so an SVG or canvas draws a few hundred rects, not thousands. */
export function runs(rows: readonly string[]): [number, number, number][] {
  const out: [number, number, number][] = [];
  rows.forEach((r, y) => {
    let x = 0;
    while (x < r.length) {
      if (r[x] !== '#') { x++; continue; }
      let e = x;
      while (e < r.length && r[e] === '#') e++;
      out.push([x, y, e - x]);
      x = e;
    }
  });
  return out;
}

/** An inline SVG of `rows`, `heightPx` CSS pixels tall (crisp at any size). */
export function rowsSvg(rows: readonly string[], heightPx: number, color: string, cls: string, label?: string): string {
  const h = rows.length;
  const w = rows[0].length;
  const width = Math.round((heightPx * w) / h);
  const body = runs(rows).map(([x, y, n]) => `<rect x="${x}" y="${y}" width="${n}" height="1"/>`).join('');
  const aria = label ? `role="img" aria-label="${label}"` : 'aria-hidden="true"';
  return `<svg class="${cls}" width="${width}" height="${heightPx}" viewBox="0 0 ${w} ${h}" shape-rendering="crispEdges" fill="${color}" ${aria}>${body}</svg>`;
}

/** Draw `rows` onto a 2D canvas with its top-left at (x, y), `cell` canvas pixels a cell. */
export function drawRows(g: CanvasRenderingContext2D, rows: readonly string[], x: number, y: number, cell: number, color: string): void {
  g.fillStyle = color;
  for (const [cx, cy, n] of runs(rows)) g.fillRect(x + cx * cell, y + cy * cell, n * cell, cell);
}
